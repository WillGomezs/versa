#!/usr/bin/env node
'use strict';
const fs=require('fs'), path=require('path'), vm=require('vm');
const root=path.resolve(__dirname,'..');
const app=fs.readFileSync(path.join(root,'app.js'),'utf8');
const css=fs.readFileSync(path.join(root,'styles.css'),'utf8');
const engineCode=fs.readFileSync(path.join(root,'adaptive-engine.js'),'utf8');
let checks=0; const failures=[]; const assert=(condition,label)=>{checks++; if(!condition) failures.push(label)};
const has=(pattern,label)=>assert(pattern.test(app),label);

has(/function\s+pretestGate\s*\(/,'Pré-teste por microlição implementado');
has(/data-pretest-confidence/,'Pré-teste registra confiança');
has(/if \(kind === "pretest"\) return correct/,'Erro de pré-teste não contamina caderno de erros');
has(/id="recall-draft"/,'Recuperação aberta sem alternativas implementada');
has(/Este texto não é salvo/,'Rascunho de recuperação aberta não é persistido');
has(/data-recall-rating/,'Autoavaliação da recuperação ativa implementada');
assert(/recallDraft:\s*""/.test(app) && /state\.recallDraft = event\.target\.value/.test(app),'Rascunho aberto fica apenas no estado efêmero da sessão');
assert(/p\.recall\[l\.id\]\s*=\s*\{\s*rating:/.test(app) && !/p\.recall\[l\.id\][^;]{0,240}draft/s.test(app),'Persistência da recuperação guarda autoavaliação, não o texto digitado');
has(/data-confidence-q/,'Confiança antes da correção implementada');
has(/erro-convicto/,'Erro convicto implementado');
has(/data-error-category/,'Classificação causal de erros implementada');
has(/alternatives-review/,'Revisão alternativa por alternativa implementada');
has(/adaptiveMixedPool/,'Prática intercalada implementada');
has(/transferPool/,'Prática de transferência implementada');
has(/data-sim-start="adaptive-mixed"/,'Acesso ao treino intercalado na interface');
has(/data-sim-start="transfer"/,'Acesso ao treino de transferência na interface');
has(/responseMs/,'Tempo de resposta persistido');
has(/VERSA PACE/,'Versa Pace exibido');
has(/function\s+studySession\s*\(/,'Sessão guiada implementada');
has(/Estudar agora — 30 min/,'Atalho de 30 minutos implementado');
has(/mastery-states/,'Quatro estados de conhecimento exibidos');
has(/GANHO DE APRENDIZAGEM/,'Comparação pré-teste versus pós-estudo exibida');
has(/REPETIÇÃO ESPAÇADA \+ RECUPERAÇÃO/,'Revisão inteligente atualizada');
assert(/\.confidence-box/.test(css),'Estilos de confiança presentes');
assert(/\.session-step/.test(css),'Estilos de sessão guiada presentes');
assert(/\.mastery-state/.test(css),'Estilos dos estados de maestria presentes');
assert(/\.error-row\.conviction/.test(css),'Destaque visual de erro convicto presente');

const sandbox={window:{}};
vm.runInNewContext(engineCode,sandbox,{filename:'adaptive-engine.js'});
const engine=sandbox.window.VERSA_ADAPTIVE_ENGINE;
assert(engine.version==='2.0.0','Mastery Engine v2.0.0 carregado');
assert(Object.keys(engine.statuses).length===4,'Quatro estados internos preservados');
assert(engine.statuses['not-started'].label==='Desconhecido','Estado Desconhecido');
assert(engine.statuses.learning.label==='Familiar','Estado Familiar');
assert(engine.statuses.consolidating.label==='Recuperável','Estado Recuperável');
assert(engine.statuses.mastered.label==='Consolidado','Estado Consolidado');

let store=engine.normalizeStore(null);
store=engine.recordAttempt(store,{kind:'lesson',questionId:'q1',lessonId:'l1',correct:false,selected:0,date:'2026-08-13',confidence:'high',responseMs:30000});
assert(store.attempts[0].confidence==='high','Confiança persistida no motor');
assert(store.attempts[0].responseMs===30000,'Tempo de resposta persistido no motor');
assert(engine.calibrationScore(store.attempts)<20,'Erro com alta confiança recebe calibração baixa');
const course={id:'t',exam:{questions:70},units:[{id:'u',title:'U',discipline:'D'}],lessons:[{id:'l1',unitId:'u',order:1,title:'L1',prerequisites:[]},{id:'l2',unitId:'u',order:2,title:'L2',prerequisites:['l1']}],flashcards:[]};
const progress={completed:['l1'],scores:{l1:80},errors:[{questionId:'q1',lessonId:'l1',status:'active',category:'erro-convicto'}],flashcards:{cards:{}},adaptive:store};
const errors=engine.errorSummary(progress);
assert(errors.conviction===1,'Erro convicto recebe prioridade própria');
const pace=engine.paceSummary(course,progress);
assert(pace.avgSeconds===30,'Ritmo médio calculado');
assert(pace.projectedSeconds===2100,'Ritmo projetado para 70 questões calculado');
const plan=engine.buildDailyPlan(course,progress,30,'2026-08-13');
assert(plan.totalMinutes===30,'Sessão adaptativa respeita 30 minutos');
assert(plan.blocks.reduce((a,b)=>a+b.minutes,0)===30,'Blocos da sessão somam 30 minutos');
assert(plan.blocks.some(b=>b.type==='conviction'),'Plano prioriza erro convicto');
assert(plan.blocks.some(b=>b.type==='new'),'Plano mantém avanço em conteúdo novo');

const payload={status:failures.length?'failed':'passed',checks,failures,summary:{masteryEngine:engine.version,pretest:true,freeRecall:true,confidence:true,errorTaxonomy:true,interleaving:true,transfer:true,pace:true,guidedSession:true}};
console.log(JSON.stringify(payload,null,2));
if(failures.length) process.exit(1);
